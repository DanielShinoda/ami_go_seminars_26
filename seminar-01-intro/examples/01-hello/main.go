// Первая программа на Go.
//
// Запуск:
//
//	go run ./seminar-01-intro/examples/01-hello
//
// Разбираем построчно — здесь нет ни одной случайной строки.
package main // имя пакета. main + функция main = исполняемая программа

import "fmt" // пакет стандартной библиотеки для форматированного ввода-вывода

func main() {
	fmt.Println("Привет, Go!")

	// Println добавляет перевод строки, Printf — нет.
	// %s — строка, %d — целое, %v — «значение как есть», %T — тип значения.
	name := "студент"
	year := 2026
	fmt.Printf("%s, курс %d года\n", name, year)
	fmt.Printf("%v имеет тип %T\n", year, year)
}
