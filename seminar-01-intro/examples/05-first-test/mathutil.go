// Пакет mathutil показывает, как в Go устроен код, который МОЖНО тестировать.
// Обратите внимание: здесь нет package main и нет func main —
// это библиотечный пакет, его нельзя запустить, но можно импортировать и тестировать.
package mathutil

// Abs возвращает модуль числа.
//
// Имя с ЗАГЛАВНОЙ буквы = экспортируемое, видно другим пакетам.
// Имя со строчной = приватное для пакета. Никаких public/private —
// регистр первой буквы и есть модификатор доступа.
func Abs(x int) int {
	if x < 0 {
		return -x
	}
	return x
}

// clamp не экспортируется: снаружи пакета его не существует.
func clamp(x, lo, hi int) int {
	if x < lo {
		return lo
	}
	if x > hi {
		return hi
	}
	return x
}
