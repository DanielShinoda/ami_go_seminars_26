// Обзорная экскурсия по типам: что нужно, чтобы прочитать чужой код на Go.
// Подробно каждую конструкцию разбираем на семинаре 2.
//
// Запуск:
//
//	go run ./seminar-01-intro/examples/04-types-tour
package main

import "fmt"

func main() {
	// Два способа объявить переменную.
	var explicit int = 10 // полная форма: видно тип
	short := 20           // короткая форма: тип выводится из значения
	fmt.Println(explicit, short)

	// Нулевое значение. В Go НЕТ неинициализированной памяти:
	// каждая переменная сразу получает нулевое значение своего типа.
	// Сравните с C++, где чтение неинициализированной переменной — UB.
	var (
		i int
		f float64
		b bool
		s string
	)
	fmt.Printf("int=%d float64=%v bool=%v string=%q\n", i, f, b, s)

	// Преобразование типов всегда явное — никаких сюрпризов.
	count := 7
	ratio := float64(count) / 2 // без float64(...) не скомпилируется
	fmt.Printf("ratio=%.2f\n", ratio)

	// Строка — это последовательность БАЙТОВ в UTF-8, а не символов.
	// Отсюда главная ловушка новичка: len() считает байты.
	word := "Привет"
	fmt.Printf("%q: len=%d байт, рун=%d\n", word, len(word), len([]rune(word)))

	// Функция может вернуть несколько значений — это идиома Go,
	// а не костыль через указатели-выходные-параметры, как в C++.
	q, r := divmod(17, 5)
	fmt.Printf("17 = 5*%d + %d\n", q, r)
}

// divmod возвращает частное и остаток.
func divmod(a, b int) (int, int) {
	return a / b, a % b
}
