package retry

import "time"

// Options — настройки повторных попыток.
type Options struct {
	// Attempts — максимальное число вызовов операции. Значение меньше 1
	// трактуется как 1 (одна попытка).
	Attempts int

	// Sleep вызывается между неудачными попытками с длительностью паузы.
	// Nil означает отсутствие пауз. После ПОСЛЕДНЕЙ попытки Sleep
	// не вызывается.
	Sleep func(d time.Duration)
}
