package assert

// TestingT — минимальная часть *testing.T, которая нужна хелперам.
//
// Хелперы принимают интерфейс, а не *testing.T, чтобы их можно было
// проверить фейком: тест подставляет свою реализацию и смотрит, что
// хелпер записал в неё.
type TestingT interface {
	// Helper помечает функцию служебной: ошибка будет указывать на
	// строку вызова хелпера.
	Helper()
	// Errorf фиксирует провал с форматированным сообщением.
	Errorf(format string, args ...any)
}
